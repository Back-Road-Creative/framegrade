"""Generated mermaid graph of the GMS pipeline.

Renders the pipeline as mermaid flowcharts from the live structures — the
19-stage long-form order grouped by sub-pipeline (``STAGE_ORDER`` +
``sub_pipelines``) and the drive phase graph (``PHASE_SPECS`` order +
prereqs). Nothing here hand-copies a stage or phase name; every node and
edge derives from those tables, so the committed doc drifts loudly when
they change.

Regenerate the committed doc with::

    python -m gomoveshift.pipeline.graph_doc

The output lives at ``docs/pipeline-graph.md`` and is pinned by
``tests/test_pipeline_graph_doc.py``: change ``STAGE_ORDER`` or
``PHASE_SPECS`` without regenerating and that test fails.
"""

from __future__ import annotations

from pathlib import Path

from .drive_orchestrator import PHASE_SPECS
from .stages import STAGE_ORDER
from .sub_pipelines import (
    IngestAndPrep,
    LightMetadata,
    PublishAndArchive,
    RenderAndDerive,
)

# Sub-pipelines in the order PipelineOrchestrator.run executes them.
_SUB_PIPELINES = (IngestAndPrep, LightMetadata, RenderAndDerive, PublishAndArchive)

# docs/pipeline-graph.md, resolved relative to this package (never cwd).
DOC_PATH = Path(__file__).resolve().parents[2] / "docs" / "pipeline-graph.md"


def render_pipeline_graph() -> str:
    """Build the committed pipeline-graph doc from the live structures."""
    idx_by_name = {stage.name: i for i, stage in enumerate(STAGE_ORDER)}

    lines: list[str] = [
        "# Pipeline graph (generated)",
        "",
        "> Generated by `python -m gomoveshift.pipeline.graph_doc` from the live",
        "> `STAGE_ORDER` and `PHASE_SPECS` tables. Do not edit by hand — regenerate.",
        "> Pinned by `tests/test_pipeline_graph_doc.py` (committed == generated).",
        "",
        "## Long-form stages (STAGE_ORDER), grouped by sub-pipeline",
        "",
        "```mermaid",
        "flowchart TD",
    ]
    for sub in _SUB_PIPELINES:
        lines.append(f"    subgraph {sub.name}")
        for stage in sub.stages:
            lines.append(f'        s_{stage.name}["{idx_by_name[stage.name]} {stage.name}"]')
        lines.append("    end")
    for prev, nxt in zip(STAGE_ORDER, STAGE_ORDER[1:]):
        lines.append(f"    s_{prev.name} --> s_{nxt.name}")
    lines.append("```")

    lines += [
        "",
        "## Drive phases (PHASE_SPECS)",
        "",
        "```mermaid",
        "flowchart TD",
    ]
    for spec in PHASE_SPECS:
        suffix = "" if spec.in_manifest else " (preview only)"
        lines.append(f'    p_{spec.name}["{spec.name}{suffix}"]')
    for spec in PHASE_SPECS:
        for prereq in spec.prereqs:
            lines.append(f"    p_{prereq} --> p_{spec.name}")
    lines.append("```")

    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    DOC_PATH.write_text(render_pipeline_graph())
    print(f"wrote {DOC_PATH}")
