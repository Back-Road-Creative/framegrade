"""Exercise the public-tree guard against real, temporary Git repositories."""

import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


GUARD = Path(__file__).resolve().parents[1] / "check_public_tree.py"


class PublicTreeTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.git("init", "--initial-branch=test")
        self.git("config", "user.name", "Test")
        self.git("config", "user.email", "test@example.invalid")
        self.write_policy([])
        self.write("src/app.py", "print('hello')\n")
        self.commit()

    def git(self, *args):
        return subprocess.run(
            ["git", "-C", str(self.root), *args],
            check=True,
            capture_output=True,
            text=True,
        ).stdout

    def write(self, name, content):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

    def write_policy(self, exceptions):
        self.write(
            "tools/public-tree-policy.json",
            json.dumps(
                {
                    "version": 1,
                    "fixture_exceptions": exceptions,
                }
            ),
        )

    def commit(self):
        self.git("add", "--all")
        self.git("commit", "--quiet", "-m", "test: fixture")

    def run_guard(self, *args, cwd=None):
        return subprocess.run(
            [sys.executable, str(GUARD), "--root", str(self.root), *args],
            cwd=cwd,
            capture_output=True,
            text=True,
        )

    def assert_code(self, result, expected):
        self.assertEqual(result.returncode, expected, result.stdout + result.stderr)

    def test_clean_source_assets_and_lockfiles_pass(self):
        for name in (
            "package-lock.json",
            "uv.lock",
            "data/cities.csv",
            "assets/logo.svg",
            "tests/fixtures/example.json",
            ".env.example",
        ):
            self.write(name, "synthetic public source\n")
        self.commit()
        self.assert_code(self.run_guard("--check-clean"), 0)

    def test_credential_and_runtime_paths_fail(self):
        for name in (
            ".env",
            ".env.production",
            "credentials.json",
            "token.json",
            "settings/secrets.json.enc",
            ".aws/config",
            "id_ed25519",
            "runtime/state.sqlite",
            "queue.db",
            "queue.db-wal",
            ".data/run.json",
        ):
            with self.subTest(path=name):
                self.write(name, "synthetic forbidden file\n")
                self.git("add", "--", name)
                result = self.run_guard()
                self.assert_code(result, 1)
                self.assertIn(name, result.stderr)
                self.git("rm", "--force", "--", name)

    def test_tracked_generated_outputs_fail_even_when_ignored(self):
        self.write(".gitignore", "build/\n__pycache__/\n")
        self.commit()
        for name in (
            "build/index.html",
            "dist/app.js",
            "src/__pycache__/app.pyc",
            "node_modules/pkg/index.js",
            ".pytest_cache/README.md",
            "coverage.xml",
        ):
            with self.subTest(path=name):
                self.write(name, "generated\n")
                self.git("add", "--force", "--", name)
                self.assert_code(self.run_guard(), 1)
                self.git("rm", "--force", "--", name)

    def test_build_changing_tracked_generated_source_fails_clean_mode(self):
        self.write("src/version.py", "VERSION = 'release'\n")
        self.commit()
        self.write("src/version.py", "VERSION = 'build timestamp'\n")
        self.assert_code(self.run_guard(), 0)
        result = self.run_guard("--check-clean")
        self.assert_code(result, 1)
        self.assertIn("src/version.py", result.stderr)

    def test_unexpected_untracked_file_fails_clean_mode(self):
        self.write("accidental-report.txt", "generated by tests\n")
        self.assert_code(self.run_guard(), 0)
        result = self.run_guard("--check-clean")
        self.assert_code(result, 1)
        self.assertIn("accidental-report.txt", result.stderr)
        self.assertTrue((self.root / "accidental-report.txt").exists())

    def test_ignored_temporary_caches_are_allowed_after_tests(self):
        self.write(".gitignore", ".pytest_cache/\n__pycache__/\nbuild/\n.venv/\n")
        self.commit()
        self.write(".pytest_cache/result", "transient\n")
        self.write("src/__pycache__/app.pyc", "transient\n")
        self.write("build/wheel.whl", "build output\n")
        self.write(".venv/lib/python3/site-packages/dependency.py", "dependency\n")
        self.assert_code(self.run_guard("--check-clean"), 0)

    def test_ignored_private_and_unknown_output_fail_clean_mode(self):
        for name, pattern in (
            (".env", ".env"),
            ("private/SECRET.ENC", "private/"),
            ("state.SQLITE", "*.SQLITE"),
            (".data/run.json", ".data/"),
            ("scratch-output/report.txt", "scratch-output/"),
            ("surprise.txt", "*.txt"),
        ):
            with self.subTest(path=name):
                self.write(".gitignore", pattern + "\n")
                self.commit()
                self.write(name, "unexpected ignored output\n")
                try:
                    self.assert_code(self.run_guard("--check-clean"), 1)
                finally:
                    (self.root / name).unlink()

    def test_staged_edit_rename_and_deletion_fail_clean_mode(self):
        self.git("mv", "src/app.py", "src/renamed.py")
        self.assert_code(self.run_guard("--check-clean"), 1)
        self.git("rm", "--force", "src/renamed.py")
        self.assert_code(self.run_guard("--check-clean"), 1)

    def test_escaping_absolute_and_cyclic_symlinks_fail(self):
        for target in ("../private", "/tmp/private", "link"):
            with self.subTest(target=target):
                os.symlink(target, self.root / "link")
                self.git("add", "link")
                try:
                    self.assert_code(self.run_guard(), 1)
                finally:
                    self.git("rm", "--force", "link")

    def test_internal_symlink_passes(self):
        os.symlink("src/app.py", self.root / "app-link")
        self.commit()
        self.assert_code(self.run_guard("--check-clean"), 0)

    def test_link_cannot_expose_ignored_private_runtime_file(self):
        self.write(".gitignore", ".env\n")
        self.write(".env", "synthetic runtime secret\n")
        os.symlink(".env", self.root / "config-link")
        self.commit()
        self.assert_code(self.run_guard(), 1)

    def test_sensitive_filenames_cover_config_formats_and_case(self):
        for name in ("secrets.yaml", "CREDENTIALS.JSON", "client_secret_123.json"):
            with self.subTest(path=name):
                self.write(name, "synthetic\n")
                self.git("add", name)
                try:
                    self.assert_code(self.run_guard(), 1)
                finally:
                    self.git("rm", "--force", name)

    def test_worktree_symlink_replaced_after_checkout_fails(self):
        os.symlink("src/app.py", self.root / "link")
        self.commit()
        (self.root / "link").unlink()
        os.symlink("../private", self.root / "link")
        self.assert_code(self.run_guard(), 1)

    def test_explicit_hashed_synthetic_fixture_passes_but_changed_bytes_fail(self):
        content = "synthetic database fixture\n"
        self.write("tests/fixtures/demo.sqlite", content)
        self.write_policy(
            [
                {
                    "path": "tests/fixtures/demo.sqlite",
                    "reason": "Synthetic empty database used by persistence tests",
                    "sha256": hashlib.sha256(content.encode()).hexdigest(),
                }
            ]
        )
        self.commit()
        self.assert_code(self.run_guard("--check-clean"), 0)
        self.write("tests/fixtures/demo.sqlite", "unreviewed replacement\n")
        self.assert_code(self.run_guard(), 1)

    def test_policy_rejects_broad_or_unpinned_exceptions(self):
        for exception in (
            {"path": "**", "reason": "anything", "sha256": "0" * 64},
            {"path": "runtime/live.db", "reason": "runtime", "sha256": "0" * 64},
            {"path": "tests/fixtures/demo.db", "reason": "synthetic"},
            {"path": "tests/fixtures/demo.db", "reason": "", "sha256": "0" * 64},
        ):
            with self.subTest(exception=exception):
                self.write_policy([exception])
                self.assert_code(self.run_guard(), 2)

    def test_missing_malformed_or_unknown_policy_fails_closed(self):
        policy = self.root / "tools/public-tree-policy.json"
        policy.unlink()
        self.assert_code(self.run_guard(), 2)
        for content in (
            "not json",
            '{"version": 99, "fixture_exceptions": []}',
            '{"version": 1, "fixture_exceptions": [], "skip": true}',
        ):
            with self.subTest(content=content):
                policy.write_text(content)
                self.assert_code(self.run_guard(), 2)

    def test_index_flags_cannot_hide_post_build_changes(self):
        for flag in ("--assume-unchanged", "--skip-worktree"):
            with self.subTest(flag=flag):
                self.git("update-index", flag, "src/app.py")
                self.write("src/app.py", "silently changed\n")
                self.assert_code(self.run_guard("--check-clean"), 1)
                self.git("update-index", "--no-assume-unchanged", "src/app.py")
                self.git("update-index", "--no-skip-worktree", "src/app.py")
                self.git("checkout", "--", "src/app.py")

    def test_untracked_or_stale_exception_policy_fails(self):
        self.write_policy(
            [
                {
                    "path": "tests/fixtures/absent.db",
                    "reason": "Synthetic fixture",
                    "sha256": "0" * 64,
                }
            ]
        )
        self.assert_code(self.run_guard(), 2)
        self.write_policy([])
        self.git("rm", "--cached", "tools/public-tree-policy.json")
        self.assert_code(self.run_guard(), 2)

    def test_parent_repository_must_not_be_silently_checked(self):
        nested = self.root / "nested"
        nested.mkdir()
        result = subprocess.run(
            [sys.executable, str(GUARD), "--root", str(nested)],
            capture_output=True,
            text=True,
        )
        self.assert_code(result, 2)

    def test_non_git_directory_fails_closed(self):
        with tempfile.TemporaryDirectory() as directory:
            result = subprocess.run(
                [sys.executable, str(GUARD), "--root", directory],
                capture_output=True,
                text=True,
            )
            self.assert_code(result, 2)


if __name__ == "__main__":
    unittest.main()
